"""Convert every legacy query to Snowflake SQL with two converters.

* llm       Claude, prompted with converter/prompt.py. Writes SQL and documentation.
* baseline  sqlglot's rule based transpiler, as a non LLM point of comparison.

Usage
    python -m converter.convert            # use cached LLM responses in llm_cache/
    python -m converter.convert --live     # call the Anthropic API and refresh the cache
                                           # (needs ANTHROPIC_API_KEY; model via LLM_MODEL)
"""

import argparse
import json
import os
import re
import sys
from datetime import datetime, timezone

import sqlglot

from converter.common import (CACHE_DIR, DOCS_DIR, LegacyQuery, converted_path,
                              load_queries)
from converter.prompt import DIALECT_NAMES, SYSTEM_PROMPT, USER_TEMPLATE

sys.path.insert(0, str(CACHE_DIR.parent / "data"))
from sample_data import SCHEMA  # noqa: E402

DEFAULT_MODEL = os.environ.get("LLM_MODEL", "claude-sonnet-5-5")


def schema_text() -> str:
    return "\n".join(
        f"  {table}({', '.join(f'{c} {t}' for c, t in cols)})"
        for table, cols in SCHEMA.items()
    )


def build_user_prompt(q: LegacyQuery) -> str:
    return USER_TEMPLATE.format(dialect_name=DIALECT_NAMES[q.dialect], title=q.title,
                                schema=schema_text(), sql=q.body)


def _extract_json(text: str) -> dict:
    match = re.search(r"\{.*\}", text, re.DOTALL)
    if not match:
        raise ValueError("LLM response did not contain a JSON object")
    return json.loads(match.group(0))


def convert_with_llm_live(q: LegacyQuery, model: str) -> dict:
    import anthropic

    client = anthropic.Anthropic()
    response = client.messages.create(
        model=model,
        max_tokens=4000,
        temperature=0,
        system=SYSTEM_PROMPT,
        messages=[{"role": "user", "content": build_user_prompt(q)}],
    )
    text = "".join(block.text for block in response.content if block.type == "text")
    result = _extract_json(text)
    result["model"] = model
    result["generated_at"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    result["prompt"] = build_user_prompt(q)
    return result


def convert_with_llm(q: LegacyQuery, live: bool, model: str) -> dict:
    cache_file = CACHE_DIR / f"{q.name}.json"
    if live:
        result = convert_with_llm_live(q, model)
        cache_file.write_text(json.dumps(result, indent=2))
        return result
    if not cache_file.exists():
        raise FileNotFoundError(f"No cached LLM response for {q.name}; run with --live")
    return json.loads(cache_file.read_text())


def convert_with_baseline(q: LegacyQuery) -> str:
    """Pure syntax transpilation. Errors are recorded as SQL comments so the
    test suite reports them instead of the pipeline crashing."""
    try:
        out = sqlglot.transpile(q.body, read=q.dialect, write="snowflake", pretty=True)
        return ";\n".join(out) + ";"
    except Exception as exc:  # sqlglot raises several exception types
        return f"-- BASELINE TRANSPILE ERROR: {type(exc).__name__}: {exc}\nSELECT NULL;"


def write_outputs(q: LegacyQuery, llm: dict, baseline_sql: str) -> None:
    header = f"-- converted from {q.name}.sql ({q.dialect})\n"
    converted_path("llm", q).write_text(header + llm["snowflake_sql"].strip() + "\n")
    converted_path("baseline", q).write_text(header + baseline_sql.strip() + "\n")

    notes = "\n".join(f"* {n}" for n in llm.get("conversion_notes", []))
    doc = (
        f"# {q.qid.upper()}: {q.title}\n\n"
        f"Source dialect: **{q.dialect}**  \n"
        f"Generated by: `{llm.get('model', 'unknown')}`\n\n"
        f"{llm['documentation'].strip()}\n\n"
        f"## Change log\n\n{notes}\n\n"
        f"## Original query\n\n```sql\n{q.body}\n```\n\n"
        f"## Snowflake query\n\n```sql\n{llm['snowflake_sql'].strip()}\n```\n"
    )
    (DOCS_DIR / f"{q.name}.md").write_text(doc)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--live", action="store_true", help="call the Anthropic API")
    parser.add_argument("--model", default=DEFAULT_MODEL)
    args = parser.parse_args()

    for q in load_queries():
        llm = convert_with_llm(q, args.live, args.model)
        baseline_sql = convert_with_baseline(q)
        write_outputs(q, llm, baseline_sql)
        print(f"converted {q.name:<34} llm: {llm.get('model', '?'):<20} baseline: sqlglot")


if __name__ == "__main__":
    main()
